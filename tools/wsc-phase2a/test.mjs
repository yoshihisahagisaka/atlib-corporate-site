import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCompaniesCsv } from './csv.mjs';
import { createLocalPrivateStore } from './local-store.mjs';
import { createSyntheticExecutor, validatePublicTarget } from './safe-executor.mjs';
import { runSyntheticBatch } from './batch.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (file) => JSON.parse(fs.readFileSync(path.join(root, '..', 'wsc-vs1', 'fixtures', file), 'utf8'));
const cloneFor = (file, targetUrl) => ({ ...read(file), targetUrl, checkedAt: '2026-10-25T00:00:00.000Z' });
const resolve = () => ['93.184.216.34'];
const csv = fs.readFileSync(path.join(root, 'fixtures', 'synthetic-batch.csv'), 'utf8');
const intake = parseCompaniesCsv(csv);
assert.equal(intake.companies.length, 5); assert.equal(intake.errors.length, 0);
assert.equal(parseCompaniesCsv('\uFEFF企業名,本店所在地,URL\nA,東京,https://example.test/\nA,東京,https://example.test/\n').errors[0].code, 'CSV_DUPLICATE_ROW');
assert.equal(parseCompaniesCsv('企業名,本店所在地,URL\nA,東京,http://example.test/\n').errors[0].code, 'CSV_URL_HTTPS_REQUIRED');
assert.throws(() => parseCompaniesCsv('企業名,所在地,URL\nA,東京,https://example.test/\n'), /CSV_HEADER_INVALID/);
assert.throws(() => validatePublicTarget('http://example.test/', resolve), /URL_NOT_ALLOWED/);
assert.throws(() => validatePublicTarget('https://localhost/', resolve), /URL_HOST_NOT_PUBLIC/);
assert.throws(() => validatePublicTarget('https://example.test/', () => ['127.0.0.1']), /DNS_NOT_PUBLIC/);
const byUrl = new Map(intake.companies.map((company, i) => [company.normalizedUrl, cloneFor(i % 2 ? 'synthetic-gaps.json' : 'synthetic-protected.json', company.normalizedUrl)]));
const executor = createSyntheticExecutor({ resolve, probe: async (url) => ({ remoteAddress: '93.184.216.34', diagnosis: byUrl.get(url) }) });
const temp = fs.mkdtempSync(path.join(root, '.test-storage-')); const store = createLocalPrivateStore(temp);
const first = await runSyntheticBatch({ csv, executor, store, batchId: 'bat_synthetic', stopAfter: 2 });
assert.equal(Object.keys(first.batch.reports).length, 2); assert.ok(first.batch.interrupted_at);
const resumed = await runSyntheticBatch({ csv, executor, store, batchId: 'bat_synthetic' });
assert.equal(Object.keys(resumed.batch.reports).length, 5); assert.ok(Object.values(resumed.batch.reports).every(r => r.status === 'REPORT_READY'));
for (const row of Object.values(resumed.batch.reports)) assert.ok(store.verifyReport('bat_synthetic', row.report_id));
const again = await runSyntheticBatch({ csv, executor, store, batchId: 'bat_synthetic' });
assert.deepEqual(again.batch, resumed.batch, 'rerun is idempotent for READY reports');
const mismatch = createSyntheticExecutor({ resolve, probe: async (url) => ({ remoteAddress: '93.184.216.34', redirectUrl: 'https://other.example/', diagnosis: byUrl.get(url) }) });
await assert.rejects(() => mismatch(intake.companies[0].normalizedUrl), /REDIRECT_REQUIRES_SEPARATE_APPROVAL/);
const rebinding = createSyntheticExecutor({ resolve: (() => { let count = 0; return () => count++ ? ['93.184.216.35'] : ['93.184.216.34']; })(), probe: async (url) => ({ remoteAddress: '93.184.216.34', diagnosis: byUrl.get(url) }) });
await assert.rejects(() => rebinding(intake.companies[0].normalizedUrl), /DNS_REBIND_DETECTED/);
assert.throws(() => createLocalPrivateStore(temp).saveReport('..', { report_id: 'x' }, { 'x.json': '{}' }), /STORE_PATH_ESCAPE/);
const timeoutExecutor = async () => { throw new Error('TIMEOUT'); };
const retryTemp = fs.mkdtempSync(path.join(root, '.test-storage-retry-')); const retryStore = createLocalPrivateStore(retryTemp);
const retryOne = await runSyntheticBatch({ csv: csv.split('\n').slice(0, 2).join('\n'), executor: timeoutExecutor, store: retryStore, batchId: 'bat_retry' });
assert.equal(Object.values(retryOne.batch.reports)[0].status, 'RETRY_PENDING');
const retryTwo = await runSyntheticBatch({ csv: csv.split('\n').slice(0, 2).join('\n'), executor: timeoutExecutor, store: retryStore, batchId: 'bat_retry' });
assert.equal(Object.values(retryTwo.batch.reports)[0].status, 'FAILED');
fs.rmSync(temp, { recursive: true, force: true }); fs.rmSync(retryTemp, { recursive: true, force: true });
console.log('WSC Phase 2A tests: PASS');
